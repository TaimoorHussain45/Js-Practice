// 1. You should have a variable named updatedCounter that uses prefix increment notation (++counter).
// 2. updatedCounter should equal to 11.
// 3. You should have a variable named finalScore that uses postfix increment notation (score++).
// 4. finalScore should equal to 8.
// 5. You should have a variable named updatedCoins that uses prefix decrement notation (--coins).
// 6. updatedCoins should equal to 2.
// 7. You should have a variable named newHealth that uses postfix decrement notation (health--).
// 8. newHealth should equal to 7.
let counter = 10;
console.log(`Counter is currently ${counter}`);

let updatedCounter = ++counter;
console.log(`Counter is now ${updatedCounter}`);

let score = 8;
console.log(`Score is currently ${score}`);

let finalScore = score ++;
console.log(`Score is still ${finalScore}`);

let coins = 3;
console.log(`Coins is currently ${coins}`);

let updatedCoins = -- coins;
console.log(`Coins is now ${updatedCoins}`);

let health = 7;
console.log(`Health is currently ${health}`);

let newHealth = health--;
console.log(`Health is still ${newHealth}`);

 